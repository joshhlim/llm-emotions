_PHRASE_RES = tuple(re.compile(rf"\b{re.escape(phrase)}\b") for phrase in _PHRASES)
_WORD_RES = tuple((word, re.compile(rf"\b{re.escape(word)}\b")) for word in _WORDS)


def _normalise(text: str) -> str:
    return text.casefold().replace("\u2019", "'")


def find_emotion_keywords(text: str) -> list[str]:
    """Return emotion names and close synonyms found in ``text``, in list order.

    The match is case-insensitive and uses word boundaries. An empty list means
    this checker did not find a listed name. It does not mean the sentence is
    free of every possible cue.
    """
    folded = _normalise(text)
    hits: list[str] = []
    for phrase, pattern in zip(_PHRASES, _PHRASE_RES, strict=True):
        if pattern.search(folded):
            hits.append(phrase)
    for word, pattern in _WORD_RES:
        if pattern.search(folded):
            hits.append(word)
    return hits


def assert_keyword_free(text: str, *, label: str) -> None:
    """Raise ``ValueError`` if ``text`` contains a listed emotion keyword."""
    hits = find_emotion_keywords(text)
    if hits:
        raise ValueError(f"{label} contains emotion keywords {hits}: {text[:120]!r}")
